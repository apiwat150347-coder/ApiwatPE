export function calculateGrade(score: number): 'A' | 'B' | 'C' | 'D' | 'F' {
  if (score >= 80) return 'A';
  if (score >= 70) return 'B';
  if (score >= 60) return 'C';
  if (score >= 50) return 'D';
  return 'F';
}

export function getGradeBadge(grade: 'A' | 'B' | 'C' | 'D' | 'F'): { label: string; color: string; bg: string } {
  switch (grade) {
    case 'A':
      return { label: 'ดีเยี่ยม (A)', color: 'text-emerald-700', bg: 'bg-emerald-50 border-emerald-300' };
    case 'B':
      return { label: 'ดีมาก (B)', color: 'text-blue-700', bg: 'bg-blue-50 border-blue-300' };
    case 'C':
      return { label: 'ปานกลาง (C)', color: 'text-amber-700', bg: 'bg-amber-50 border-amber-300' };
    case 'D':
      return { label: 'พอใช้ (D)', color: 'text-orange-700', bg: 'bg-orange-50 border-orange-300' };
    case 'F':
      return { label: 'ควรส่งเสริม (F)', color: 'text-rose-700', bg: 'bg-rose-50 border-rose-300' };
  }
}
